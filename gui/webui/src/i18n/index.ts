function isSupportedLocale(
  value: string | undefined,
): value is SupportedLocale {
  return value != null && supportedLocales.includes(value as SupportedLocale);
}

function readPersistedLocale() {
  if (typeof document === 'undefined') return undefined;
  const value = document.cookie
    .split(';')
    .map((part) => part.trim())
    .find((part) => part.startsWith(`${LOCALE_COOKIE_KEY}=`))
    ?.split('=')[1];
  return isSupportedLocale(value) ? value : undefined;
}

export function resolveInitialLocale(): SupportedLocale {
  const persisted = readPersistedLocale();
  if (persisted) return persisted;
  if (typeof navigator === 'undefined') return fallbackLocale;
  const candidates = [...(navigator.languages ?? []), navigator.language];
  return candidates.some((locale) => /^zh(?:-|$)/i.test(locale))
    ? 'zh-CN'
    : fallbackLocale;
}

export const i18n = createI18n({
  legacy: false,
  locale: resolveInitialLocale(),
  fallbackLocale,
  messages: { 'en-US': enUS, 'zh-CN': zhCN },
});

export function setLocale(locale: SupportedLocale) {
  i18n.global.locale.value = locale;
  if (typeof document !== 'undefined')
    document.cookie = `${LOCALE_COOKIE_KEY}=${locale}; Path=/; Max-Age=31536000; SameSite=Lax`;
}
